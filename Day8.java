public class DeklarasiVariabel {

    public static void main(String[] args) {
        //Deklarasi//
        String nama;
        int umur;
        //Inisialisasi//
        nama = "Hasmira";
        umur = 18;
        System.out.println(nama);
        System.out.println(umur);

        //update//
        nama = "mira";
        umur = 19;
        System.out.println(nama);
        System.out.println(umur);

    }
}
